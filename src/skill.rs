//! From memory to repository skill (1.10, from Beacon: `beacon memory skills install`). A memory
//! is retrieved when the recall brings it; a skill is loaded by the agent itself when its description
//! fits the task, and if it is pushed to the repository it reaches the whole team and every agent, with
//! Omoikane installed or without it. `.agents/skills/<name>/SKILL.md` is read by Codex, Cursor, Gemini CLI,
//! Copilot, OpenCode and others; Claude Code reads `.claude/skills`. Both copies are written (a symbolic
//! link needs permissions on Windows).
//!
//! What Beacon doesn't do: each file carries in its header the memory's id and a fingerprint of what was
//! generated. With it we know if the memory changed afterwards (the skill is **outdated** and `refresh`
//! brings it up to date) or if someone edited the file by hand (**edited**: not overwritten without `force`). Nor is
//! a skill written whose text looks like it holds a secret, because the file is going to end up in a commit.

use crate::memoria::{Memory, Kind};
use anyhow::{Result, bail};
use rusqlite::Connection;
use serde::Serialize;
use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};

/// The repository's skill folders: the common one and Claude Code's.
pub const FOLDERS: [&str; 2] = [".agents/skills", ".claude/skills"];
/// The maximum length of the name and of the description (Agent Skills specification).
const MAX_NAME: usize = 64;
const MAX_DESCRIPTION: usize = 1024;

/// Which folders are written to.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Target {
    Both,
    Agents,
    Claude,
}

impl Target {
    pub fn parse(text: Option<&str>) -> Result<Target> {
        Ok(match text.map(|t| t.trim().to_lowercase()).as_deref() {
            None | Some("") | Some("both") | Some("ambas") => Target::Both,
            Some("agents") | Some("agentes") => Target::Agents,
            Some("claude") => Target::Claude,
            Some(other) => bail!(crate::tr!("unknown target «{other}»: use both, agents or claude", "destino desconocido «{other}»: usa both, agents o claude")),
        })
    }

    fn folders(self) -> &'static [&'static str] {
        match self {
            Target::Both => &FOLDERS,
            Target::Agents => &FOLDERS[..1],
            Target::Claude => &FOLDERS[1..],
        }
    }
}

/// What state a skill generated by Omoikane is in.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum State {
    /// It says the same as the memory.
    UpToDate,
    /// The memory changed afterwards: `refresh` brings it up to date.
    Outdated,
    /// Someone edited it by hand: not overwritten without `force`.
    Edited,
    /// The memory no longer exists (forgotten, or from another database).
    Orphan,
}

/// A repository skill generated by Omoikane.
#[derive(Clone, Debug, Serialize)]
pub struct Skill {
    /// The path of the `SKILL.md`, relative to the repository and with `/`.
    pub path: String,
    pub memory_id: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    pub state: State,
}

/// What `write` did in each folder.
#[derive(Clone, Debug, Serialize)]
pub struct Written {
    pub path: String,
    /// `created`, `updated`, `unchanged`, or `skipped` with the reason in `reason`.
    pub action: &'static str,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub reason: Option<String>,
}

/// The part of a `SKILL.md` header that matters.
#[derive(Debug, Default, PartialEq)]
struct Header {
    id: Option<String>,
    hash: Option<String>,
    description: String,
    body: String,
}

/// The skill's name: the title without accents, lowercase, with letters, digits and `-`.
pub fn name(m: &Memory) -> String {
    let mut r = String::new();
    for c in crate::nombres::fold_accents(&m.title).chars() {
        if c.is_ascii_alphanumeric() {
            r.push(c.to_ascii_lowercase());
        } else if !r.is_empty() && !r.ends_with('-') {
            r.push('-');
        }
        if r.len() >= MAX_NAME {
            break;
        }
    }
    let r = r.trim_matches('-').to_string();
    if r.is_empty() { format!("memoria-{}", id_suffix(&m.id)) } else { r }
}

fn id_suffix(id: &str) -> String {
    id.chars().rev().take(6).collect::<Vec<_>>().into_iter().rev().collect::<String>().to_lowercase()
}

/// The description, which decides when the agent loads it: the title and, in a recipe, its
/// `when:` words; otherwise, the files it refers to. One line.
pub fn description(m: &Memory) -> String {
    let title = m.title.trim().trim_end_matches('.');
    let when = if m.kind == Kind::Procedure { when_words(m) } else { Vec::new() };
    let mut d = if !when.is_empty() {
        let w = when.join(", ");
        if in_spanish(m) { format!("{title}. Úsala cuando: {w}.") } else { format!("{title}. Use it when: {w}.") }
    } else if !m.paths.is_empty() {
        let p = m.paths.join(", ");
        if in_spanish(m) { format!("{title}. Se aplica a: {p}.") } else { format!("{title}. Applies to: {p}.") }
    } else {
        format!("{title}.")
    };
    d = d.split_whitespace().collect::<Vec<_>>().join(" ");
    if d.chars().count() > MAX_DESCRIPTION {
        d = d.chars().take(MAX_DESCRIPTION - 1).collect::<String>() + "…";
    }
    d
}

/// The words of a recipe's `when:` (or `cuando:`) line, as the user wrote them.
fn when_words(m: &Memory) -> Vec<String> {
    m.content
        .lines()
        .filter_map(|l| {
            let l = l.trim().trim_start_matches(['-', '*', ' ']);
            let n = l.to_lowercase();
            ["when:", "cuando:"].iter().find(|p| n.starts_with(*p)).map(|p| l[p.len()..].to_string())
        })
        .flat_map(|r| r.split(',').map(|w| w.trim().trim_matches(['"', '\'', '«', '»', '`', '.']).to_string()).collect::<Vec<_>>())
        .filter(|w| w.chars().count() >= 3)
        .collect()
}

/// The body: the title, the memory's text and where it comes from.
fn body(m: &Memory) -> String {
    let short: String = m.id.chars().take(12).collect();
    let date = m.updated_at.get(..10).unwrap_or(&m.updated_at);
    format!(
        "# {}\n\n{}\n\n---\n\n{}\n",
        m.title.trim(),
        m.content.trim(),
        if in_spanish(m) {
            format!(
                "Generada desde la memoria de Omoikane `{short}` ({}, cambiada el {date}). `omoi skill --refresh` la pone al día cuando cambia la memoria; lo que se edite aquí a mano se respeta.",
                m.kind
            )
        } else {
            format!(
                "Generated from Omoikane memory `{short}` ({}, changed {date}). `omoi skill --refresh` brings it up to date when the memory changes; edits made here by hand are kept.",
                m.kind
            )
        }
    )
}

/// Whether the memory is in Spanish (the skill's fixed words go in its language, not in the
/// CLI's): accents, eñes and opening marks, or more frequent Spanish words than English ones.
fn in_spanish(m: &Memory) -> bool {
    let t = format!(" {} {} ", m.title, m.content).to_lowercase();
    let marks = t.chars().filter(|c| "áéíóúñ¿¡".contains(*c)).count();
    let count = |ws: &[&str]| ws.iter().map(|w| t.matches(&format!(" {w} ")).count()).sum::<usize>();
    let es = count(&["de", "que", "el", "la", "los", "las", "y", "en", "para", "con", "por", "un", "una", "se", "no"]);
    let en = count(&["the", "and", "of", "to", "is", "with", "for", "in", "it", "on", "a", "an", "not", "be"]);
    marks * 2 + es > en
}

/// The fingerprint of what was generated: the description and the body, with line endings as `\n` (git on
/// Windows may turn them into `\r\n`) and no trailing spaces.
fn fingerprint(description: &str, body: &str) -> String {
    let normal = |t: &str| t.replace("\r\n", "\n").trim_end().to_string();
    let h = Sha256::digest(format!("{}\n{}", normal(description), normal(body)).as_bytes());
    h.iter().take(8).map(|b| format!("{b:02x}")).collect()
}

/// The whole `SKILL.md` of memory `m` with name `n`.
pub fn generate(m: &Memory, n: &str) -> String {
    let d = description(m);
    let c = body(m);
    let h = fingerprint(&d, &c);
    // The description goes as JSON text, which is also valid YAML: that way neither `:` nor `#` break it.
    format!(
        "---\nname: {n}\ndescription: {}\nmetadata:\n  omoikane-id: \"{}\"\n  omoikane-hash: \"{h}\"\n---\n\n{c}",
        serde_json::to_string(&d).unwrap_or_default(),
        m.id
    )
}

fn read_header(text: &str) -> Option<Header> {
    let t = text.replace("\r\n", "\n");
    let rest = t.strip_prefix("---\n")?;
    let end = rest.find("\n---\n")?;
    let (head, body) = (&rest[..end], &rest[end + 5..]);
    let mut c = Header { body: body.trim_start_matches('\n').to_string(), ..Default::default() };
    let value = |v: &str| -> String {
        let v = v.trim();
        serde_json::from_str::<String>(v).unwrap_or_else(|_| v.trim_matches(['"', '\'']).to_string())
    };
    for line in head.lines() {
        let l = line.trim();
        if let Some(v) = line.strip_prefix("description:") {
            c.description = value(v);
        } else if let Some(v) = l.strip_prefix("omoikane-id:") {
            c.id = Some(value(v));
        } else if let Some(v) = l.strip_prefix("omoikane-hash:") {
            c.hash = Some(value(v));
        }
    }
    Some(c)
}

/// The root of the project's repository, or an error if the session isn't in one.
fn repo_root(project: &str) -> Result<PathBuf> {
    if project.is_empty() || crate::proyecto::is_general(project) {
        bail!(crate::tr!(
            "skills go in a repository: run it inside one (or pass --dir)",
            "las skills van en un repositorio: lánzalo dentro de uno (o pasa --dir)"
        ));
    }
    Ok(PathBuf::from(project))
}

fn relative(root: &Path, p: &Path) -> String {
    p.strip_prefix(root).unwrap_or(p).to_string_lossy().replace('\\', "/")
}

/// The `SKILL.md` files generated by Omoikane in `folder` (from `FOLDERS`): (path, header).
fn generated_in(root: &Path, folder: &str) -> Vec<(PathBuf, Header)> {
    let Ok(dir) = std::fs::read_dir(root.join(folder)) else { return Vec::new() };
    let mut v: Vec<(PathBuf, Header)> = dir
        .flatten()
        .map(|e| e.path().join("SKILL.md"))
        .filter_map(|p| {
            let c = read_header(&std::fs::read_to_string(&p).ok()?)?;
            c.id.as_ref()?;
            Some((p, c))
        })
        .collect();
    v.sort_by(|a, b| a.0.cmp(&b.0));
    v
}

fn state_of(db: &Connection, c: &Header) -> (State, Option<Memory>) {
    let Some(m) = c.id.as_deref().and_then(|id| crate::memoria::get(db, id).ok()) else { return (State::Orphan, None) };
    if c.hash.as_deref() != Some(fingerprint(&c.description, &c.body).as_str()) {
        return (State::Edited, Some(m));
    }
    let current = fingerprint(&description(&m), &body(&m));
    (if c.hash.as_deref() == Some(current.as_str()) { State::UpToDate } else { State::Outdated }, Some(m))
}

/// A project memory that could be a skill, with the reason.
#[derive(Clone, Debug, Serialize)]
pub struct Suggestion {
    pub id: String,
    pub title: String,
    pub kind: Kind,
    /// In how many sessions the agent applied it (journal).
    pub applied_sessions: i64,
    pub recall_count: i64,
}

/// How many sessions applying a memory make it a candidate (recipes always are).
pub const MIN_APPLIED: i64 = 2;
/// How many are proposed at most.
pub const MAX_SUGGESTIONS: usize = 5;

/// The project's memories (not the global ones, nor those of its space or role: a skill belongs to the
/// repository) that fit as a skill and aren't one yet: recipes, and those the agent applied in
/// [`MIN_APPLIED`] sessions or more. First the most applied, then the most recalled. Without those that
/// look like they hold a secret. This is what gets them used: without it, you have to go and look up the id.
pub fn suggestions(db: &Connection, project: &str) -> Result<Vec<Suggestion>> {
    repo_root(project)?;
    let Some((pid, _)) = crate::proyecto::resolve(db, project)? else { return Ok(Vec::new()) };
    if pid == 0 {
        return Ok(Vec::new());
    }
    let already: std::collections::BTreeSet<String> = list(db, project)?.into_iter().map(|s| s.memory_id).collect();
    let all = crate::memoria::recent(db, &crate::memoria::Scope::from_project(db, project)?, None, usize::MAX >> 1)?;
    let mut r: Vec<Suggestion> = Vec::new();
    for m in all.into_iter().filter(|m| m.project_id == pid && !already.contains(&m.id)) {
        let (applied, _) = crate::diario::applied(db, &m.id)?;
        if m.kind != Kind::Procedure && applied < MIN_APPLIED {
            continue;
        }
        if !crate::secretos::findings(&format!("{}\n{}", m.title, m.content)).is_empty() {
            continue;
        }
        r.push(Suggestion { id: m.id, title: m.title, kind: m.kind, applied_sessions: applied, recall_count: m.recall_count });
    }
    r.sort_by(|a, b| (b.applied_sessions, b.recall_count).cmp(&(a.applied_sessions, a.recall_count)).then_with(|| a.id.cmp(&b.id)));
    r.truncate(MAX_SUGGESTIONS);
    Ok(r)
}

/// The memory asked for to make it a skill: an id (or its start) or some words. With words,
/// it searches what is visible from the project: if one clearly comes out ahead (it's the only one, or
/// it has more of the query's words than the second), that one; otherwise, an error listing the candidates
/// with their id, to choose.
pub fn resolve(db: &mut Connection, project: &str, requested: &str) -> Result<String> {
    let p = requested.trim();
    if !p.contains(char::is_whitespace)
        && let Ok(id) = crate::memoria::resolve_id(db, p)
    {
        return Ok(id);
    }
    let o = crate::buscar::SearchOptions { scope: crate::memoria::Scope::from_project(db, project)?, kind: None, tags: Vec::new(), limit: 5 };
    let mut rs = crate::buscar::search_without_recording(db, p, &o)?;
    // The search scores those sharing words almost the same; whoever asks for a skill names its
    // title. They are sorted by how many of the query's words are in the title (without accents), and on a
    // tie the search order stays.
    let words = |t: &str| -> std::collections::BTreeSet<String> {
        crate::nombres::fold_accents(t).split(|c: char| !c.is_alphanumeric()).filter(|w| w.chars().count() >= 2).map(str::to_string).collect()
    };
    let query = words(p);
    let in_title = |m: &Memory| words(&m.title).intersection(&query).count();
    rs.sort_by_key(|r| std::cmp::Reverse(in_title(&r.memory)));
    match rs.as_slice() {
        [] => bail!(crate::tr!("no memory matches «{p}»", "ninguna memoria encaja con «{p}»")),
        [one] => Ok(one.memory.id.clone()),
        [a, b, ..] if in_title(&a.memory) > in_title(&b.memory) => Ok(a.memory.id.clone()),
        several => {
            let list: Vec<String> = several.iter().map(|r| format!("  {}  {}", r.memory.id.chars().take(12).collect::<String>(), r.memory.title)).collect();
            bail!(crate::tr!(
                "several memories match «{p}»; pick one by its id:\n{}",
                "varias memorias encajan con «{p}»; elige una por su id:\n{}",
                list.join("\n")
            ))
        }
    }
}

/// The skills Omoikane generated in `project`'s repository, with their state.
pub fn list(db: &Connection, project: &str) -> Result<Vec<Skill>> {
    let root = repo_root(project)?;
    let mut r = Vec::new();
    for folder in FOLDERS {
        for (p, c) in generated_in(&root, folder) {
            let (state, m) = state_of(db, &c);
            r.push(Skill { path: relative(&root, &p), memory_id: c.id.unwrap_or_default(), title: m.map(|m| m.title), state });
        }
    }
    Ok(r)
}

/// Writes (or brings up to date) the skill of memory `id` in `project`'s repository. With `dry_run`
/// it touches nothing and says what it would do. Without `force` it doesn't overwrite a file edited by hand nor one that isn't
/// Omoikane's, and doesn't write a memory that looks like it holds a secret.
pub fn write(db: &Connection, project: &str, id: &str, target: Target, force: bool, dry_run: bool) -> Result<Vec<Written>> {
    let root = repo_root(project)?;
    let m = crate::memoria::get(db, id)?;
    crate::memoria::in_scope(db, &crate::memoria::Scope::from_project(db, project)?, &m.id)?;
    let secrets = crate::secretos::kinds(&crate::secretos::findings(&format!("{}\n{}", m.title, m.content)));
    if !secrets.is_empty() && !force {
        bail!(crate::tr!(
            "the memory looks like it holds a secret ({}): a skill ends up in a commit. Fix the memory, or pass force if it is a false alarm",
            "la memoria parece llevar un secreto ({}): una skill acaba en un commit. Corrige la memoria, o pasa force si es una falsa alarma",
            crate::secretos::summary(&secrets)
        ));
    }
    let mut r = Vec::new();
    for folder in target.folders() {
        // If there's already a skill for this memory (maybe with the name of an earlier title), that same one.
        let own = generated_in(&root, folder).into_iter().find(|(_, c)| c.id.as_deref() == Some(m.id.as_str()));
        let path = match &own {
            Some((p, _)) => p.clone(),
            None => {
                let base = name(&m);
                let p = root.join(folder).join(&base).join("SKILL.md");
                // Another skill has the name: the end of the id is appended.
                if p.exists() && !force { root.join(folder).join(format!("{base}-{}", id_suffix(&m.id))).join("SKILL.md") } else { p }
            }
        };
        let n = path.parent().and_then(|d| d.file_name()).map(|d| d.to_string_lossy().into_owned()).unwrap_or_else(|| name(&m));
        let text = generate(&m, &n);
        let rel = relative(&root, &path);
        let before = std::fs::read_to_string(&path).ok();
        let skip = |reason: String| Written { path: rel.clone(), action: "skipped", reason: Some(reason) };
        let action = match (&before, &own) {
            (Some(a), _) if a.replace("\r\n", "\n") == text => "unchanged",
            (Some(_), Some((_, c))) if !force && state_of(db, c).0 == State::Edited => {
                r.push(skip(crate::tr!("edited by hand: pass force to replace it", "editada a mano: pasa force para sustituirla").to_string()));
                continue;
            }
            (Some(_), None) if !force => {
                r.push(skip(crate::tr!("a skill that isn't from Omoikane is already there", "ahí ya hay una skill que no es de Omoikane").to_string()));
                continue;
            }
            (Some(_), _) => "updated",
            (None, _) => "created",
        };
        if !dry_run && action != "unchanged" {
            if let Some(d) = path.parent() {
                std::fs::create_dir_all(d)?;
            }
            std::fs::write(&path, &text)?;
        }
        r.push(Written { path: rel, action, reason: None });
    }
    Ok(r)
}

/// Brings the repository's outdated skills up to date (not the edited nor the orphaned ones).
pub fn refresh(db: &Connection, project: &str, dry_run: bool) -> Result<Vec<Written>> {
    let root = repo_root(project)?;
    let mut r = Vec::new();
    for folder in FOLDERS {
        for (p, c) in generated_in(&root, folder) {
            let (State::Outdated, Some(m)) = state_of(db, &c) else { continue };
            let n = p.parent().and_then(|d| d.file_name()).map(|d| d.to_string_lossy().into_owned()).unwrap_or_else(|| name(&m));
            if !dry_run {
                std::fs::write(&p, generate(&m, &n))?;
            }
            r.push(Written { path: relative(&root, &p), action: "updated", reason: None });
        }
    }
    Ok(r)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn memory(title: &str, content: &str, kind: Kind) -> Memory {
        Memory {
            id: "01M64R0KKD0AXYZ123456789AB".into(),
            kind,
            title: title.into(),
            content: content.into(),
            updated_at: "2026-11-16T10:00:00Z".into(),
            ..Default::default()
        }
    }

    #[test]
    fn valid_names() {
        let m = memory("Publicar una versión de Omoikane (crates.io)", "", Kind::Procedure);
        assert_eq!(name(&m), "publicar-una-version-de-omoikane-crates-io");
        let long = memory(&"palabra ".repeat(30), "", Kind::Fact);
        assert!(name(&long).len() <= MAX_NAME && !name(&long).ends_with('-'));
        assert_eq!(name(&memory("«»", "", Kind::Fact)), "memoria-6789ab");
    }

    #[test]
    fn the_recipe_says_when() {
        let m = memory("Publicar una versión", "1. tag\n2. push\n\nwhen: publica, saca versión", Kind::Procedure);
        let d = description(&m);
        assert!(d.contains("publica") && d.contains("saca versión"), "{d}");
        assert!(d.contains("Úsala cuando"), "{d}");
        let mut g = memory("Don't kill the emulator", "taskkill leaves the lock file behind", Kind::Gotcha);
        g.paths = vec!["scripts/emu.ps1".into()];
        assert_eq!(description(&g), "Don't kill the emulator. Applies to: scripts/emu.ps1.");
    }

    #[test]
    fn the_header_is_read_and_the_fingerprint_matches() {
        let m = memory("Título: con dos puntos # y almohadilla", "Paso 1\nPaso 2", Kind::Procedure);
        let t = generate(&m, "titulo");
        let c = read_header(&t).unwrap();
        assert_eq!(c.id.as_deref(), Some(m.id.as_str()));
        assert_eq!(c.description, description(&m));
        assert_eq!(c.hash.as_deref(), Some(fingerprint(&c.description, &c.body).as_str()));
        // With Windows line endings, the same fingerprint.
        let c2 = read_header(&t.replace('\n', "\r\n")).unwrap();
        assert_eq!(fingerprint(&c2.description, &c2.body), c.hash.unwrap());
        // Edited: another fingerprint.
        let c3 = read_header(&t.replace("Paso 2", "Paso 2 bis")).unwrap();
        assert_ne!(fingerprint(&c3.description, &c3.body), c3.hash.unwrap());
    }

    #[test]
    fn targets() {
        assert_eq!(Target::parse(None).unwrap(), Target::Both);
        assert_eq!(Target::parse(Some("claude")).unwrap().folders(), &[".claude/skills"]);
        assert!(Target::parse(Some("otro")).is_err());
    }
}
